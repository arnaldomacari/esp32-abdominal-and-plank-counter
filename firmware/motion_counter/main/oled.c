static esp_err_t oled_cmd(uint8_t cmd)
{
    uint8_t data[2] = {0x00, cmd};
    return i2c_bus_write_bytes(OLED_ADDR, data, sizeof(data));
}

static esp_err_t oled_data(const uint8_t *data, size_t len)
{
    uint8_t buffer[17];
    size_t offset = 0;

    while (offset < len) {
        size_t chunk = len - offset;

        if (chunk > 16) {
            chunk = 16;
        }

        buffer[0] = 0x40;
        memcpy(&buffer[1], &data[offset], chunk);

        esp_err_t ret = i2c_bus_write_bytes(OLED_ADDR, buffer, chunk + 1);

        if (ret != ESP_OK) {
            return ret;
        }

        offset += chunk;
    }

    return ESP_OK;
}

esp_err_t oled_init(void)
{
    vTaskDelay(pdMS_TO_TICKS(100));

    uint8_t cmds[] = {
        0xAE,
        0xD5, 0x80,
        0xA8, 0x3F,
        0xD3, 0x00,
        0x40,
        0x8D, 0x14,
        0x20, 0x00,
        0xA1,
        0xC8,
        0xDA, 0x12,
        0x81, 0xCF,
        0xD9, 0xF1,
        0xDB, 0x40,
        0xA4,
        0xA6,
        0xAF
    };

    for (size_t i = 0; i < sizeof(cmds); i++) {
        esp_err_t ret = oled_cmd(cmds[i]);
        if (ret != ESP_OK) {
            ESP_LOGE(TAG, "Erro inicializando OLED: %s", esp_err_to_name(ret));
            return ret;
        }
    }

    oled_clear();
    ESP_LOGI(TAG, "OLED SSD1306 iniciado em 0x%02X", OLED_ADDR);

    return ESP_OK;
}

void oled_set_cursor(int col, int page)
{
    if (col < 0) col = 0;
    if (col > 127) col = 127;
    if (page < 0) page = 0;
    if (page > 7) page = 7;

    oled_cmd(0xB0 + page);
    oled_cmd(0x00 + (col & 0x0F));
    oled_cmd(0x10 + ((col >> 4) & 0x0F));
}

void oled_clear(void)
{
    uint8_t zeros[OLED_WIDTH];
    memset(zeros, 0x00, sizeof(zeros));

    for (int page = 0; page < OLED_PAGES; page++) {
        oled_set_cursor(0, page);
        oled_data(zeros, sizeof(zeros));
    }

    oled_set_cursor(0, 0);
}

void oled_write_text(const char *text)
{
    while (*text) {
        char c = *text++;

        if ((unsigned char)c > 127) {
            c = '?';
        }

        uint8_t ch[6] = {0};

        memcpy(ch, font5x7[(uint8_t)c], 5);
        ch[5] = 0x00;

        oled_data(ch, sizeof(ch));
    }
}

void oled_printf(int col, int page, const char *fmt, ...)
{
    char buffer[32];

    va_list args;
    va_start(args, fmt);
    vsnprintf(buffer, sizeof(buffer), fmt, args);
    va_end(args);

    oled_set_cursor(col, page);
    oled_write_text(buffer);
}